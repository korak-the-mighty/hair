  // Returns a binary mask {w,h,m:Uint8Array} for the text.
  ND.textMask = function (text, opts = {}) {
    const font = opts.small ? F3 : F5;
    const gw = opts.small ? 3 : 5, gh = opts.small ? 5 : 7;
    const s = opts.scale || 1;
    const gap = opts.gap != null ? opts.gap : s;
    const vertical = !!opts.vertical;
    const italic = opts.italic || 0; // pixels of shear per glyph height
    const chars = [...text.toUpperCase()];
    const cw = gw * s, ch = gh * s;
    const w = vertical ? cw + italic : chars.length * cw + (chars.length - 1) * gap + italic;
    const h = vertical ? chars.length * ch + (chars.length - 1) * gap : ch;
    const m = new Uint8Array(w * h);
    chars.forEach((chr, i) => {
      const g = font[chr] || font[' '];
      const ox = vertical ? 0 : i * (cw + gap);
      const oy = vertical ? i * (ch + gap) : 0;
      for (let gy = 0; gy < gh; gy++)
        for (let gx = 0; gx < gw; gx++) {
          if (g[gy][gx] !== '#') continue;
          for (let sy = 0; sy < s; sy++)
            for (let sx = 0; sx < s; sx++) {
              const yy = oy + gy * s + sy;
              const sh = italic ? Math.round(((ch - 1 - (gy * s + sy)) / Math.max(1, ch - 1)) * italic) : 0;
              const xx = ox + gx * s + sx + sh;
              if (xx >= 0 && xx < w) m[yy * w + xx] = 1;
            }
        }
    });
    return { w, h, m };
  };

  // Neon tube text. Draws into colour pb (col) and emissive pb (glow).
  // core/tube are [r,g,b]; letters get a bright core, saturated halo.
  ND.neonText = function (col, glow, text, x, y, core, tube, opts = {}) {
    const mk = ND.textMask(text, opts);
    ND.neonMask(col, glow, mk, x, y, core, tube, opts);
    return mk;
  };

  ND.neonMask = function (col, glow, mk, x, y, core, tube, opts = {}) {
    const halo = opts.halo !== false;
    const on = opts.on !== false;
    const dim = on ? 1 : 0.18;
    const { w, h, m } = mk;
    const at = (xx, yy) => (xx >= 0 && yy >= 0 && xx < w && yy < h ? m[yy * w + xx] : 0);
    if (halo) {
      for (let yy = -1; yy <= h; yy++)
        for (let xx = -1; xx <= w; xx++) {
          if (at(xx, yy)) continue;
          let n = 0;
          for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) n += at(xx + dx, yy + dy);
          if (!n) continue;
          const a = Math.min(1, 0.35 + n * 0.12) * (on ? 1 : 0.5);
          col.blend(x + xx, y + yy, ND.scale(tube, on ? 0.95 : 0.35), a);
          if (glow && on) glow.blend(x + xx, y + yy, ND.scale(tube, 0.55), a);
        }
    }
    for (let yy = 0; yy < h; yy++)
      for (let xx = 0; xx < w; xx++) {
        if (!m[yy * w + xx]) continue;
        const c = on ? core : ND.mix(tube, [30, 20, 40], 0.7);
        col.set(x + xx, y + yy, ND.pack(c[0] * (on ? 1 : dim + 0.3), c[1] * (on ? 1 : dim + 0.3), c[2] * (on ? 1 : dim + 0.3)));
        if (glow && on) glow.set(x + xx, y + yy, ND.pack(tube[0] * 0.8 + core[0] * 0.2, tube[1] * 0.8 + core[1] * 0.2, tube[2] * 0.8 + core[2] * 0.2));
      }
  };

  // A neon tube along a path of points (1px core + halo).
  ND.neonPath = function (col, glow, pts, core, tube, opts = {}) {
    const width = opts.width || 1;
    const set = new Set();
    const pb = col;
    for (let i = 0; i + 1 < pts.length; i++) {
      pb.lineFn(pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1], (x, y) => {
        set.add(x + ',' + y);
        if (width > 1) set.add(x + 1 + ',' + y);
      });
    }
    ND.neonSet(col, glow, set, core, tube, opts);
  };

  // Neon from a set of "x,y" keys.
  ND.neonSet = function (col, glow, set, core, tube, opts = {}) {
    const pts = [...set].map((k) => k.split(',').map(Number));
    if (opts.halo !== false) {
      const seen = new Set();
      for (const [x, y] of pts)
        for (let dy = -1; dy <= 1; dy++)
          for (let dx = -1; dx <= 1; dx++) {
            const k = x + dx + ',' + (y + dy);
            if (set.has(k) || seen.has(k)) continue;
            seen.add(k);
            col.blend(x + dx, y + dy, tube, dx && dy ? 0.45 : 0.75);
            if (glow) glow.blend(x + dx, y + dy, ND.scale(tube, 0.6), dx && dy ? 0.4 : 0.7);
          }
    }
    for (const [x, y] of pts) {
      col.set(x, y, ND.pack(core[0], core[1], core[2]));
      if (glow) glow.set(x, y, ND.pack(tube[0] * 0.75 + core[0] * 0.25, tube[1] * 0.75 + core[1] * 0.25, tube[2] * 0.75 + core[2] * 0.25));
    }
  };

